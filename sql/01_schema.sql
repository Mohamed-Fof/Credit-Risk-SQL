-- =============================================================================
-- Risk Analytics — schéma de la base (PostgreSQL 15 ou plus)
-- Exécution : psql -d risk_analytics_db -f sql/01_schema.sql   (ou dans DBeaver)
--
-- Choix de conception :
--  * ON DELETE RESTRICT : supprimer un client ne doit JAMAIS effacer silencieusement
--    l'historique de ses prêts (obligation de conservation des données bancaires).
--  * Le retard (DPD) n'est PAS stocké : il se déduit des dates et des paiements.
--    Une donnée calculée et stockée finit toujours par devenir incohérente.
--  * NUMERIC pour l'argent : un FLOAT ne représente pas exactement 0,10 €.
-- =============================================================================

DROP TABLE IF EXISTS provisions_mensuelles, journal_statuts, echantillons_modele,
                     predictions_scoring_ml, echeancier_remboursements, demandes_pret,
                     clients, parametres_risque CASCADE;

-- -----------------------------------------------------------------------------
-- 0. Paramètres métier : une seule source de vérité, modifiable sans toucher au code
-- -----------------------------------------------------------------------------
CREATE TABLE parametres_risque (
    cle         VARCHAR(40)  PRIMARY KEY,
    valeur      NUMERIC,
    valeur_date DATE,
    description TEXT         NOT NULL,
    CONSTRAINT une_seule_valeur CHECK ((valeur IS NULL) <> (valeur_date IS NULL))
);
