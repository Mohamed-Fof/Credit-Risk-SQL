-- -----------------------------------------------------------------------------
-- 1. Clients : le référentiel des emprunteurs
-- -----------------------------------------------------------------------------
CREATE TABLE clients (
    client_id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_complet        VARCHAR(100)  NOT NULL,
    email              VARCHAR(120)  NOT NULL UNIQUE,
    age                SMALLINT      NOT NULL CHECK (age BETWEEN 18 AND 100),
    revenu_annuel      NUMERIC(12,2) NOT NULL CHECK (revenu_annuel > 0),
    statut_logement    VARCHAR(20)   NOT NULL
                       CHECK (statut_logement IN ('locataire', 'proprietaire', 'credit_immobilier', 'autre')),
    anciennete_emploi  NUMERIC(4,1)  CHECK (anciennete_emploi >= 0),   -- NULL = inconnue
    anciennete_credit  SMALLINT      NOT NULL CHECK (anciennete_credit >= 0),
    defaut_anterieur   BOOLEAN       NOT NULL,
    date_inscription   DATE          NOT NULL,
    CONSTRAINT anciennete_coherente CHECK (anciennete_emploi IS NULL OR anciennete_emploi <= age - 14)
);

-- -----------------------------------------------------------------------------
-- 2. Demandes de prêt : le dossier, sa décision et son statut de remboursement
-- -----------------------------------------------------------------------------
CREATE TABLE demandes_pret (
    pret_id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id              BIGINT        NOT NULL REFERENCES clients (client_id) ON DELETE RESTRICT,
    montant_demande        NUMERIC(12,2) NOT NULL CHECK (montant_demande > 0),
    duree_mois             SMALLINT      NOT NULL CHECK (duree_mois BETWEEN 6 AND 120),
    taux_interet           NUMERIC(5,2)  NOT NULL CHECK (taux_interet > 0 AND taux_interet < 40),
    taux_impute            BOOLEAN       NOT NULL DEFAULT false,   -- taux absent de la source, remplacé par la médiane
    motif_pret             VARCHAR(25)   NOT NULL
                           CHECK (motif_pret IN ('etudes', 'sante', 'creation_entreprise', 'personnel',
                                                 'travaux', 'regroupement_dettes')),
    note_risque            CHAR(1)       NOT NULL CHECK (note_risque BETWEEN 'A' AND 'G'),
    date_demande           DATE          NOT NULL,
    date_decision          DATE,
    date_premiere_echeance DATE,
    statut_dossier         VARCHAR(12)   NOT NULL DEFAULT 'en_attente'
                           CHECK (statut_dossier IN ('en_attente', 'accorde', 'refuse')),
    -- statut de remboursement : n'a de sens que pour un prêt accordé
    statut_pret            VARCHAR(12)   CHECK (statut_pret IN ('sain', 'en_retard', 'en_defaut', 'solde')),
    CONSTRAINT decision_apres_demande CHECK (date_decision >= date_demande),
    CONSTRAINT statut_si_accorde      CHECK ((statut_dossier = 'accorde') = (statut_pret IS NOT NULL))
);

-- -----------------------------------------------------------------------------
-- 3. Échéancier : une ligne par mensualité, avec le suivi des paiements
-- -----------------------------------------------------------------------------
CREATE TABLE echeancier_remboursements (
    echeance_id        BIGINT        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    pret_id            BIGINT        NOT NULL REFERENCES demandes_pret (pret_id) ON DELETE RESTRICT,
    num_echeance       SMALLINT      NOT NULL CHECK (num_echeance > 0),
    date_echeance      DATE          NOT NULL,
    montant_du         NUMERIC(12,2) NOT NULL CHECK (montant_du > 0),
    part_capital       NUMERIC(12,2) NOT NULL CHECK (part_capital >= 0),
    part_interets      NUMERIC(12,2) NOT NULL CHECK (part_interets >= 0),
    capital_restant_du NUMERIC(12,2) NOT NULL CHECK (capital_restant_du >= 0),  -- après cette échéance
    montant_paye       NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (montant_paye >= 0),
    date_paiement      DATE,                                -- date du paiement complet, NULL sinon
    CONSTRAINT une_echeance_par_numero UNIQUE (pret_id, num_echeance),
    CONSTRAINT paiement_borne          CHECK (montant_paye <= montant_du),
    CONSTRAINT date_si_solde           CHECK ((date_paiement IS NOT NULL) = (montant_paye = montant_du))
);

-- -----------------------------------------------------------------------------
-- 4. Prédictions des modèles : un registre versionné (plusieurs modèles par prêt)
-- -----------------------------------------------------------------------------
CREATE TABLE predictions_scoring_ml (
    prediction_id      BIGINT        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    pret_id            BIGINT        NOT NULL REFERENCES demandes_pret (pret_id) ON DELETE RESTRICT,
    version_modele     VARCHAR(40)   NOT NULL,
    est_champion       BOOLEAN       NOT NULL DEFAULT false,   -- le modèle qui décide en production
    probabilite_defaut NUMERIC(7,6)  NOT NULL CHECK (probabilite_defaut BETWEEN 0 AND 1),
    score_points       SMALLINT,                                -- grille de score uniquement
    seuil_decision     NUMERIC(4,3)  NOT NULL CHECK (seuil_decision BETWEEN 0 AND 1),
    decision           VARCHAR(10)   NOT NULL CHECK (decision IN ('accorder', 'refuser')),
    shap_top_feature   VARCHAR(50),                             -- NULL pour les modèles sans SHAP
    shap_top_valeur    NUMERIC(8,4),
    date_prediction    TIMESTAMP     NOT NULL,
    CONSTRAINT une_prediction_par_version UNIQUE (pret_id, version_modele),
    CONSTRAINT decision_coherente CHECK ((decision = 'refuser') = (probabilite_defaut >= seuil_decision))
);

-- Registre du découpage apprentissage / test : indispensable pour évaluer un modèle honnêtement
CREATE TABLE echantillons_modele (
    pret_id     BIGINT      PRIMARY KEY REFERENCES demandes_pret (pret_id) ON DELETE RESTRICT,
    echantillon VARCHAR(13) NOT NULL CHECK (echantillon IN ('apprentissage', 'test'))
);

-- -----------------------------------------------------------------------------
-- Index : PostgreSQL indexe automatiquement les clés primaires et les contraintes UNIQUE,
-- mais PAS les clés étrangères. Les index ci-dessous sont ceux qui servent vraiment.
-- -----------------------------------------------------------------------------
CREATE INDEX idx_prets_client ON demandes_pret (client_id);                 -- jointure client → prêts
CREATE INDEX idx_prets_statut ON demandes_pret (statut_pret);               -- filtres de pilotage
-- index PARTIEL : seules les échéances non soldées, celles que l'on cherche pour le retard
CREATE INDEX idx_echeances_impayees
    ON echeancier_remboursements (pret_id, date_echeance)
    WHERE montant_paye < montant_du;
-- (pret_id, num_echeance) et (pret_id, version_modele) sont déjà indexés par leurs contraintes UNIQUE.
